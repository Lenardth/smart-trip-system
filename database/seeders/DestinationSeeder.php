    public function run(): void
    {
        DB::statement('DELETE FROM destinations');
        // Note: No AUTO_INCREMENT reset needed — SQLite handles IDs automatically

        $now   = Carbon::now()->toDateTimeString();
        $batch = [];
        $i     = 1;
        $total = 0;

        foreach ($this->destinations() as $d) {
            $batch[] = [
                'name'          => $d[0],
                'country'       => $d[1],
                'region'        => $d[2] ?? $this->determineRegion($d[1]),
                'category'      => $d[3] ?? 'general',
                'mood'          => $d[4] ?? 'cultural',
                'price_from'    => $d[5] ?? rand(500, 3000),
                'description'   => $d[6] ?? $this->generateDescription($d[0], $d[1]),
                'image_url'     => $d[7] ?? $this->getPlaceholderImage($d[0]),
                'badge'         => $d[8] ?? null,
                'is_hidden_gem' => $d[9] ?? 0,
                'match_score'   => $d[10] ?? null,
                'is_active'     => 1,
                'sort_order'    => $i++,
                'created_at'    => $now,
                'updated_at'    => $now,
            ];
            $total++;

            if (count($batch) >= 100) {
                DB::table('destinations')->insert($batch);
                $batch = [];
                $this->command->info("  ✓ Inserted {$total} destinations...");
            }
        }

        if (!empty($batch)) {
            DB::table('destinations')->insert($batch);
        }

        $count      = DB::table('destinations')->count();
        $hiddenGems = DB::table('destinations')->where('is_hidden_gem', 1)->count();

        $this->command->info('');
        $this->command->info('✓========================================✓');
        $this->command->info('  SEEDING COMPLETE');
        $this->command->info('✓========================================✓');
        $this->command->info("  Total destinations : {$count}");
        $this->command->info("  Hidden gems        : {$hiddenGems}");
        $this->command->info('✓========================================✓');
    }

