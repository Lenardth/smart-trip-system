    private function generateDescription(string $name, string $country): string
    {
        $templates = [
            "Discover the hidden charms of {$name}, {$country} — a destination that rewards the curious traveler with authentic experiences and unforgettable moments.",
            "Escape the crowds and explore {$name} in {$country}, where local traditions and natural beauty create the perfect off-the-beaten-path adventure.",
            "{$name}, {$country} awaits those seeking something different — a place where every corner reveals a new story and every interaction feels genuine.",
            "Step into the magic of {$name}, {$country} — a captivating destination that combines rich heritage with warm hospitality and stunning surroundings.",
            "Experience the undiscovered beauty of {$name}, {$country} — from breathtaking landscapes to vibrant local culture, this gem will steal your heart.",
        ];
        return $templates[array_rand($templates)];
    }

    /**
     * Picsum gives a stable, real photo for every destination based on its name.
     * No API key needed, never goes down, always returns a real image.
     */
    private function getPlaceholderImage(string $name): string
    {
        $seed = abs(crc32($name)) % 1000;
        return "https://picsum.photos/seed/{$seed}/600/400";
    }

